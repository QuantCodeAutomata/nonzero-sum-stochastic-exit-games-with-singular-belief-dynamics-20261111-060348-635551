"""Construction of the belief process (Z_t) as a limit of approximations
(Z_t^delta) solving the ODE (Eq. 5.1):

    dZ_t^delta = - Z_t^delta * lambda^delta(X_t, Y(Z_t^delta)) dt,   Z_0^delta = 1,

with

    lambda^delta(x, y) = (r*y - D(x)) / max(m(x; y) - y, delta) * 1{x <= alpha(y)}.

The underlying diffusion (X_t) is simulated with the closed-form GBM solution
X_t = X_0 * exp(-t + W_t) (Sec. 8), consistent with d(log X_t) =
(DRIFT_COEF - 0.5*VOL_COEF^2) dt + VOL_COEF dW_t = -dt + dW_t for the
Section 8 parameters.
"""

from __future__ import annotations

from dataclasses import dataclass

import numpy as np
from scipy.integrate import solve_ivp
from scipy.interpolate import interp1d

from src.config import ODE_ATOL, ODE_RTOL, R
from src.fundamental_solutions import phi
from src.resolvents import D_profit

# The GBM trajectory (X_t) used as input to the belief-process ODE is
# synthetic data generated by data/generate_synthetic.py (simulate_gbm), not
# by this module: src/ contains only the model and the ODE solver.


@dataclass
class ThetaUniform:
    """Uniform distribution of exit values theta on [theta_L, theta_U]."""

    theta_l: float
    theta_u: float

    def Y(self, z: np.ndarray | float) -> np.ndarray | float:
        """Inverse CDF Y(z) = theta_l + (theta_u - theta_l) * z (Eq. 4.2)."""
        return self.theta_l + (self.theta_u - self.theta_l) * np.clip(z, 0.0, 1.0)

    def Z(self, theta: np.ndarray | float) -> np.ndarray | float:
        """CDF F(theta) = (theta - theta_l) / (theta_u - theta_l)."""
        return (theta - self.theta_l) / (self.theta_u - self.theta_l)


class BoundaryInterpolators:
    """Linear interpolators of alpha(theta), beta(theta) and the associated
    value-function level a_theta(alpha(theta)), b_theta(beta(theta)) on a
    pre-tabulated theta grid, for fast repeated evaluation inside the ODE
    right-hand side."""

    def __init__(
        self,
        theta_grid: np.ndarray,
        alpha_vals: np.ndarray,
        a_at_alpha: np.ndarray,
        beta_vals: np.ndarray,
        b_at_beta: np.ndarray,
    ) -> None:
        self._alpha = interp1d(theta_grid, alpha_vals, kind="linear",
                                fill_value=(alpha_vals[0], alpha_vals[-1]),
                                bounds_error=False)
        self._a_at_alpha = interp1d(theta_grid, a_at_alpha, kind="linear",
                                     fill_value=(a_at_alpha[0], a_at_alpha[-1]),
                                     bounds_error=False)
        self._beta = interp1d(theta_grid, beta_vals, kind="linear",
                               fill_value=(beta_vals[0], beta_vals[-1]),
                               bounds_error=False)
        self._b_at_beta = interp1d(theta_grid, b_at_beta, kind="linear",
                                    fill_value=(b_at_beta[0], b_at_beta[-1]),
                                    bounds_error=False)

    def alpha(self, theta):
        return self._alpha(theta)

    def beta(self, theta):
        return self._beta(theta)

    def m_value(self, x, theta, M_hat_fn):
        """Monopoly value function m(x; theta) (Eq. 3.2 analogue)."""
        beta_theta = self._beta(theta)
        b_at_beta = self._b_at_beta(theta)
        x_arr = np.asarray(x, dtype=float)
        continuation = b_at_beta * phi(np.clip(x_arr, 1e-300, None)) + M_hat_fn(x_arr)
        return np.where(x_arr > beta_theta, continuation, theta)


def lambda_delta(
    x: float, y: float, delta: float, boundaries: BoundaryInterpolators, M_hat_fn
) -> float:
    """Right-hand side rate lambda^delta(x, y) of Eq. (5.1)."""
    if x > boundaries.alpha(y):
        return 0.0
    m_val = float(boundaries.m_value(x, y, M_hat_fn))
    denom = max(m_val - y, delta)
    return (R * y - float(D_profit(x))) / denom


def solve_Z_delta(
    t_grid: np.ndarray,
    x_path: np.ndarray,
    delta: float,
    theta_dist: ThetaUniform,
    boundaries: BoundaryInterpolators,
    M_hat_fn,
    method: str = "RK45",
) -> np.ndarray:
    """Solve the ODE (5.1) for a single delta along a fixed X_t path.

    `x_path` is interpolated linearly in between the time grid points, as
    specified in the methodology (paper_pipeline, Step 6).
    """
    x_interp = interp1d(t_grid, x_path, kind="linear", bounds_error=False,
                         fill_value=(x_path[0], x_path[-1]))

    def rhs(t: float, z: np.ndarray) -> np.ndarray:
        z0 = float(np.clip(z[0], 0.0, 1.0))
        x_t = float(x_interp(t))
        y_t = float(theta_dist.Y(z0))
        lam = lambda_delta(x_t, y_t, delta, boundaries, M_hat_fn)
        return [-z0 * lam]

    solution = solve_ivp(
        rhs, (t_grid[0], t_grid[-1]), [1.0], t_eval=t_grid,
        method=method, rtol=ODE_RTOL, atol=ODE_ATOL, max_step=t_grid[1] - t_grid[0],
    )
    if not solution.success:
        raise RuntimeError(f"ODE solver failed for delta={delta}: {solution.message}")
    return np.clip(solution.y[0], 0.0, 1.0)


def belief_process_limit(z_delta_paths: list[np.ndarray]) -> np.ndarray:
    """Pointwise infimum over delta of the approximating paths (Sec. 5
    construction of (Z_t) as the limit of (Z_t^delta) as delta -> 0)."""
    stacked = np.vstack(z_delta_paths)
    return np.min(stacked, axis=0)
